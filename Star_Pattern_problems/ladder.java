package Star_Pattern_problems;

public class ladder {
    public static void main(String[] args) {
        int n=10;
        int m=9;
        for (int i = 1; i<=n; i++) {
            for (int j= 1; j<=m; j++) {
                System.out.print(n);
            }
            System.out.println(" ");
        }
    }
    
}
